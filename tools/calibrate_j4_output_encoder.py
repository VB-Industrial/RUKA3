"""Offline J4 LUT: RUKA2 equal-raw nodes, bidirectional mean and 1-2-1 filter.

RUKA2 uses TMC steps over a bounded span. Here the reference is motor encoder
counts / robot_config gear, with periodic interpolation across a full cycle.
"""
import hashlib
import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "build/g474-joint4/diagnostics"
CPR, NODES, GEAR = 16384, 256, 36


def read(name):
    path = DATA / name
    rows = [json.loads(s) for s in path.read_text().splitlines() if s.startswith("{")]
    p = np.array([r["value"]["real32"]["value"] for r in rows if r.get("register") == "get_pos"])
    motor = p[:, 3] * CPR + p[:, 0]
    output = p[:, 4] * CPR + p[:, 1]
    if abs(output[-1] - output[0]) < CPR:
        raise ValueError(f"{name}: incomplete output cycle")
    return motor, output, hashlib.sha256(path.read_bytes()).hexdigest()


def correction_at_nodes(motor, output):
    direction = np.sign(output[-1] - output[0])
    corrections = []
    for phase in np.arange(NODES) * (CPR // NODES):
        crossings = []
        for turn in range(int(np.floor(output.min() / CPR)) - 1,
                          int(np.ceil(output.max() / CPR)) + 1):
            target = phase + turn * CPR
            for i in range(1, len(output)):
                if (direction * output[i-1] <= direction * target <= direction * output[i]
                        and direction * (output[i] - output[i-1]) > 0):
                    fraction = (target - output[i-1]) / (output[i] - output[i-1])
                    reference = motor[i-1] + fraction * (motor[i] - motor[i-1])
                    crossings.append(reference / GEAR - target)
        if not crossings:
            raise ValueError(f"Missing calibration node {phase}")
        corrections.append(np.mean(crossings))
    return np.array(corrections)


def residual_metrics(motor, output, nodes):
    raw = output.astype(int) % CPR
    index = raw >> 6
    fraction = (raw % 64) / 64
    correction = nodes[index] + fraction * (nodes[(index + 1) % NODES] - nodes[index])
    residual = motor / GEAR - output - correction
    residual -= np.median(residual)
    return {"rms_deg": float(np.sqrt(np.mean(residual**2)) * 360 / CPR),
            "p95_abs_deg": float(np.percentile(np.abs(residual), 95) * 360 / CPR)}


def main():
    a, da, hash_a = read("cal-forward.jsonl")
    b, db, hash_b = read("cal-reverse.jsonl")
    forward = correction_at_nodes(a, da)
    reverse = correction_at_nodes(b, db)
    averaged = (forward + reverse) / 2
    nodes = np.rint((np.roll(averaged, 1) + 2 * averaged + np.roll(averaged, -1)) / 4).astype(int)
    if np.max(np.abs(nodes)) > 32767:
        raise ValueError("Correction does not fit int16")
    slopes = 1 + (np.roll(nodes, -1) - nodes) / (CPR // NODES)
    if slopes.min() <= 0:
        raise ValueError("Calibrated scale is not monotonic")
    metrics = {"joint": 4, "gear_ratio": GEAR, "cpr": CPR, "nodes": NODES,
               "method": "RUKA2 equal-raw nodes / bidirectional mean / periodic 1-2-1",
               "motor_encoder_sign": -1, "output_encoder_sign": -1,
               "samples_forward": len(a), "samples_reverse": len(b),
               "sources_sha256": {"cal-forward.jsonl": hash_a, "cal-reverse.jsonl": hash_b},
               "forward_fit": residual_metrics(a, da, nodes),
               "reverse_fit": residual_metrics(b, db, nodes),
               "forward_table_on_reverse": residual_metrics(b, db, np.rint(forward)),
               "reverse_table_on_forward": residual_metrics(a, da, np.rint(reverse)),
               "minimum_mapping_slope": float(slopes.min()), "maximum_mapping_slope": float(slopes.max()),
               "zero_policy": "Correct current and zero through the same LUT; preserve physical zero."}
    header = ("#pragma once\n#include \"../output_encoder_calibration.hpp\"\n\n"
              "// J4: +/-0.4 A, gear 36; raw ticks already have output_encoder_sign=-1.\n"
              "// RUKA2 bidirectional table / periodic 1-2-1 smoothing.\n"
              "// Generated by tools/calibrate_j4_output_encoder.py.\n"
              "namespace ruka3 {\ninline constexpr OutputEncoderCalibration kJ4OutputEncoderCalibration{{\n")
    header += "\n".join("    " + ", ".join(map(str, nodes[i:i+8])) + "," for i in range(0, NODES, 8))
    header += "\n}};\n} // namespace ruka3\n"
    # Historical offline fit only. Runtime calibration now lives in EEPROM.
    dest = DATA / "legacy-calibration/j4_output_encoder.hpp"
    dest.parent.mkdir(exist_ok=True)
    dest.write_text(header)
    (DATA / "output-calibration-fit.json").write_text(json.dumps(metrics, indent=2) + "\n")
    print(json.dumps(metrics, indent=2))


if __name__ == "__main__":
    main()
